using Hearthcast.Data.Snapshots;
using Hearthcast.Data.Classification;

namespace Hearthcast.Api.Snapshots.Contracts;

public sealed record FinancedAssetSnapshotResponse(
    Guid Id,
    Guid HouseholdId,
    Guid SnapshotId,
    Guid FinancedAssetId,
    string AssetName,
    Guid CategoryId,
    string CategoryName,
    FinancialType FinancialType,
    Guid GroupId,
    string GroupName,
    string CurrencyCode,
    string CountryCode,
    DateOnly? PurchaseDate,
    decimal? PurchasePrice,
    decimal OriginalLoanAmount,
    bool HasWithdrawalFacility,
    bool IncludeInHousehold,
    decimal? CurrentValuation,
    SnapshotValueOrigin CurrentValuationValueOrigin,
    DateOnly? CurrentValuationLastConfirmedDate,
    DatePrecision? CurrentValuationLastConfirmedPrecision,
    Guid? CurrentValuationCarriedFromSnapshotId,
    decimal? OutstandingLoanBalance,
    SnapshotValueOrigin OutstandingLoanBalanceValueOrigin,
    DateOnly? OutstandingLoanBalanceLastConfirmedDate,
    DatePrecision? OutstandingLoanBalanceLastConfirmedPrecision,
    Guid? OutstandingLoanBalanceCarriedFromSnapshotId,
    decimal? AvailableToWithdraw,
    SnapshotValueOrigin AvailableToWithdrawValueOrigin,
    DateOnly? AvailableToWithdrawLastConfirmedDate,
    DatePrecision? AvailableToWithdrawLastConfirmedPrecision,
    Guid? AvailableToWithdrawCarriedFromSnapshotId,
    IReadOnlyList<SnapshotShareResponse> Owners,
    IReadOnlyList<Guid> LoanHolderSnapshotPersonIds,
    IReadOnlyList<SnapshotShareResponse> HouseholdAllocations)
{
    internal static FinancedAssetSnapshotResponse From(FinancedAssetSnapshot value) => new(
        value.Id,
        value.HouseholdId,
        value.SnapshotId,
        value.FinancedAssetId,
        value.AssetName,
        value.CategoryId,
        value.CategoryName,
        value.FinancialType,
        value.GroupId,
        value.GroupName,
        value.CurrencyCode,
        value.CountryCode,
        value.PurchaseDate,
        value.PurchasePrice,
        value.OriginalLoanAmount,
        value.HasWithdrawalFacility,
        value.IncludeInHousehold,
        value.CurrentValuation,
        value.CurrentValuationValueOrigin,
        value.CurrentValuationLastConfirmedDate,
        value.CurrentValuationLastConfirmedPrecision,
        value.CurrentValuationCarriedFromSnapshotId,
        value.OutstandingLoanBalance,
        value.OutstandingLoanBalanceValueOrigin,
        value.OutstandingLoanBalanceLastConfirmedDate,
        value.OutstandingLoanBalanceLastConfirmedPrecision,
        value.OutstandingLoanBalanceCarriedFromSnapshotId,
        value.AvailableToWithdraw,
        value.AvailableToWithdrawValueOrigin,
        value.AvailableToWithdrawLastConfirmedDate,
        value.AvailableToWithdrawLastConfirmedPrecision,
        value.AvailableToWithdrawCarriedFromSnapshotId,
        value.Owners.OrderBy(row => row.SnapshotPersonId).Select(row => new SnapshotShareResponse(row.SnapshotPersonId, row.ShareBasisPoints)).ToArray(),
        value.LoanHolders.Select(row => row.SnapshotPersonId).OrderBy(id => id).ToArray(),
        value.HouseholdAllocations.OrderBy(row => row.SnapshotPersonId).Select(row => new SnapshotShareResponse(row.SnapshotPersonId, row.ShareBasisPoints)).ToArray());
}
